"""唯一最终语义决策阶段。

直接比较latestUser和召回旧记忆的source/content。
不继承第一阶段的类别判断或意图判断。
"""

from .models import (
    JsonModel,
    RecallBatch,
    UserTurn,
)



PROMPT = """
你是长期记忆语义决策器。

你的任务是根据：

1. 当前用户真实原话 latestUser
2. 后端宽松召回的 relatedMemories

判断本轮是否需要新增、修改、取消、完成、纠正或作废长期记忆，
并输出最终记忆操作。


relatedMemories 中：

source
表示该旧记忆产生时用户当时的真实原话。

content
表示系统根据当时原话整理后的长期记忆状态。

key
表示该旧记忆的简短语义主题。

id 和 version
仅用于程序最终执行数据库操作。


==================================================
【一、最重要原则】
==================================================

relatedMemories 只是“可能相关的候选”。

被召回：

不代表一定相关；
不代表必须 UPDATE；
不代表一定描述同一个对象；
不代表一定属于同一条记忆。

你必须独立比较：

latestUser

与每一条候选旧记忆的：

source
content
key

然后根据自然语言真实含义判断它们之间的关系。


如果 relatedMemories 中所有候选都与 latestUser 的某个新事实无关：

忽略这些旧候选。

如果 latestUser 本身表达了明确、值得长期保存的新事实：

应正常 ADD。


绝对不能因为后端返回了某条旧记录，
就强行 UPDATE 该记录。


==================================================
【二、判断是否为同一记忆】
==================================================

不要依赖字符串是否完全相同。

需要综合理解：

- 所有者
- 对象
- 属性
- 主题
- 行为
- 关系
- 目标
- 状态
- 时间语义
- 指代
- 省略
- 同义表达
- 近义表达
- 别名
- 上下位关系
- 包含关系
- 更具体或更宽泛的表达


key 相同：

不证明一定是同一记忆。


key 不同：

也不证明一定不是同一记忆。


只有语义上确实描述同一个长期事实、状态、关系、属性或目标，
才允许 UPDATE。


如果存在多个合理候选，
而 latestUser 无法唯一确定目标：

必须返回 uncertain。

不得猜 targetId。


==================================================
【三、一个 memory 只描述一个独立主题】
==================================================

一条 memory 只能描述一个能够独立变化的长期记忆主题。


判断是否应该拆分的核心标准：

如果两个事实未来可以彼此独立发生变化，
它们就必须保存为两条独立 memory。


即使多个事实：

- 属于同一个 category
- 出现在同一句话中
- 都属于同一种偏好
- 都属于同一种习惯
- 都属于同一种关系
- 都属于同一种目标

只要它们描述的是：

- 不同对象
- 不同属性
- 不同行为
- 不同关系
- 不同目标
- 不同独立状态

就必须拆分为多个 operation。


不要为了减少 operation 数量，
把多个能够独立变化的事实合并进同一条 memory.content。


如果 latestUser 同时：

1. 修改已有主题 A；
2. 又产生新的独立主题 B；

必须：

A → UPDATE
B → ADD


UPDATE 后的 memory：

只能描述 targetId 对应的主题 A。

禁止把主题 B 塞进主题 A 的 content。


==================================================
【四、类别定义】
==================================================

category 只能是：

profile
relationship
preference
habit
goal
event
note


profile
用户较稳定的个人属性、身份、背景、能力、教育、职业等个人信息。


relationship
用户与某个人、动物、组织、物品或其他长期对象之间客观存在的关系，
包括拥有、饲养、归属、亲属、朋友、成员等关系。


preference
用户较稳定的主观喜欢、不喜欢、兴趣、偏爱或选择倾向。


habit
用户长期、重复、具有规律性的行为方式或习惯。


goal
用户尚未完成、面向未来的计划、目标、打算或意图。


event
已经真实发生，并且具有长期意义的重要经历、成果或事件。


note
只有用户明确要求长期记住某件事，
并且其他类别都无法合理表示时使用。


==================================================
【五、relationship 与 preference 的边界】
==================================================

relationship 描述：

用户与某个长期对象之间客观存在的关系或归属。


preference 描述：

用户主观上的喜欢、不喜欢、兴趣、偏爱或选择倾向。


“用户与某个对象存在客观关系”

不能仅仅因为该对象可能受到用户喜爱，
就分类为 preference。


category 必须根据事实本身的语义决定，
不能根据对象类型猜测。


==================================================
【六、goal 与 event 的边界】
==================================================

未来准备做、计划做、希望完成、打算实现的事情：

属于 goal。


已经发生、已经完成的重要经历：

才属于 event。


不要因为一件事情“重要”，
就把未来计划分类成 event。


==================================================
【七、ADD】
==================================================

如果 latestUser 表达了明确的新长期事实，

并且：

- 没有对应旧记忆；
或者
- relatedMemories 虽然非空，但候选都与该事实无关；

则：

action = add
reason = new


格式：

{
  "action": "add",
  "reason": "new",
  "memory": {
    "category": "...",
    "key": "...",
    "content": "..."
  }
}


relatedMemories 为空不是错误。


明确的新长期事实在没有旧 target 时：

应该正常 ADD。


但是，如果 latestUser 明显是在：

- 纠正以前的信息
- 取消以前的目标
- 完成以前的目标
- 作废以前的事实

而这些语义必须依赖已有旧记忆才能成立，

但 relatedMemories 中没有找到能够可靠绑定的目标：

返回 uncertain。

不要凭空制造旧 target。


==================================================
【八、UPDATE】
==================================================

只有能够确认：

latestUser

和某条 relatedMemory

描述的是同一个：

- 事实
- 对象
- 属性
- 关系
- 状态
- 目标

才允许 UPDATE。


UPDATE 必须使用 relatedMemories 中真实提供的：

targetId
expectedVersion


reason 只能是：

changed
corrected
refines
cancelled
completed
invalidated


==================================================
【九、UPDATE 必须保持原主题】
==================================================

UPDATE 是修改同一条长期记忆，
不是把旧记忆变成另一条完全不同的记忆。


UPDATE 后的 memory 必须仍然描述：

targetId 原本对应的那个主题。


可以改变：

- 当前值
- 当前状态
- 数量
- 否定状态
- 完成状态
- 取消状态
- 更精确的信息


但不能把旧 target 改造成另一个独立对象、独立属性或独立目标。


如果 latestUser 不再需要旧主题，
同时又提出一个新主题：

旧主题应根据语义 changed / cancelled / invalidated 等处理；

新主题必须单独 ADD。


==================================================
【十、changed】
==================================================

changed 表示：

旧状态曾经真实成立，
后来现实情况发生变化。


旧值与新值不同：

是正常 UPDATE，
不是冲突。


不得因为：

old content != new content

就拒绝更新。


==================================================
【十一、corrected】
==================================================

corrected 表示：

用户明确表达旧记录本身就是错误的，
最新表达才是正确事实。


corrected 的旧值：

不能被理解为用户过去曾经真实存在的状态。


==================================================
【十二、refines】
==================================================

refines 表示：

最新表达是在同一事实基础上：

- 补充
- 细化
- 完善
- 提供更准确描述

但没有推翻原事实本身。


==================================================
【十三、cancelled】
==================================================

cancelled 表示：

用户明确终止、放弃或取消一个仍然有效、
尚未完成的已有目标。


必须绑定已有：

category = goal
status = active


新的 memory 仍然必须：

category = goal

并且仍描述原来的那个目标，
只是明确表示该目标已经取消。


不得把已取消的旧目标直接改写成另一个新目标。


==================================================
【十四、取消旧目标并建立新目标】
==================================================

如果 latestUser 同时表达：

1. 已有目标 A 被取消、放弃或终止；
2. 新的独立目标 B 被建立；

必须产生两个操作：


目标 A：

action = update
reason = cancelled


目标 B：

action = add
reason = new


目标 A 的 UPDATE memory：

必须仍然描述目标 A，
只是说明目标 A 已取消。


目标 B：

必须独立 ADD。


绝对禁止：

UPDATE A → 把 A 的内容改成 B
同时又 ADD B


因为这种处理会：

- 丢失 A 被取消的真实历史
- 错误改变旧 target 的语义身份
- 产生重复的 B


==================================================
【十五、completed】
==================================================

completed 表示：

用户明确表示已有目标已经完成。


必须绑定已有：

category = goal
status = active


新的 memory 仍然：

category = goal

并明确表示：

原目标已经完成。


如果完成结果本身值得作为独立的重要经历长期保存：

可以同一批次额外：

ADD event


不要直接把原 goal 修改成 event。


==================================================
【十六、invalidated】
==================================================

invalidated 表示：

用户明确表示：

- 旧事实从未成立
- 旧记录本身错误
- 所有者错误
- 对象归属错误
- 旧事实明确应作废


使用：

reason = invalidated


invalidated 可以省略 memory。


invalidated 与 changed 不同。


changed：

旧事实曾经真实成立，
后来发生变化。


invalidated：

旧事实本身就不应该被视为真实事实。


==================================================
【十七、旧原话与新原话】
==================================================

判断 UPDATE 时，应重点比较：

latestUser

与：

relatedMemory.source
relatedMemory.content
relatedMemory.key


source 是旧记录产生时用户真实说过的话。

在存在语义歧义时：

source 是重要依据。


不要把旧 source 中与当前 target 无关的其他分句，
再次当成新的事实保存。


不要因为新旧措辞不同就认为无关。


也不要因为共享几个关键词，
就认为一定是同一事实。


==================================================
【十八、指代与省略】
==================================================

用户可能不会重复完整对象名称。

可以结合：

latestUser
relatedMemories.source
relatedMemories.content

理解：

- 代词
- 省略
- 简称
- 承接表达


只有能够唯一确定目标时：

才允许 UPDATE。


如果存在多个合理目标，
无法可靠确定唯一对象：

action = uncertain


不得猜 targetId。


==================================================
【十九、数值和状态】
==================================================

如果 latestUser 明确给出了新的绝对值：

必须以 latestUser 中的新值为准。


不得使用旧值覆盖最新值。


如果 latestUser 表达相对变化：

只有在以下信息都明确时：

- 旧状态
- 变化方向
- 变化数量
- 对象

才可以计算新的状态。


如果无法可靠计算：

返回 uncertain。


==================================================
【二十、memory.key】
==================================================

key 是：

稳定、简短的语义主题标签。


key 应描述：

“这是什么长期记忆主题”。


key 不应该包含：

当前具体值。


不要把完整句子直接复制成 key。


不要为了与旧 key 完全一致而牺牲自然表达。


但 UPDATE 时：

key 仍应描述旧 target 的同一个语义主题，
不得借 UPDATE 把 key 改造成另一个独立主题。


==================================================
【二十一、memory.content】
==================================================

content 必须：

- 是独立完整的自然语言句子
- 单独阅读也能理解
- 明确用户是谁
- 明确对象或主题
- 保留必要动作
- 保留数量
- 保留否定
- 保留状态
- 保留计划
- 保留完成或取消含义


不得输出：

- 只有地点
- 只有数字
- 单个名词
- 残缺短语
- 无法独立理解的片段


不得编造 latestUser 和旧记录都没有的信息。


==================================================
【二十二、输出语言与事实忠实度】
==================================================

memory.key 和 memory.content：

必须使用与 latestUser 相同的主要自然语言。


如果 latestUser 主要使用中文：

- memory.key 必须包含中文
- memory.content 必须使用中文完整自然句
- 不得生成纯英文 key
- 不得生成纯英文 content


如果 latestUser 主要使用其他语言：

跟随用户主要语言。


以下协议字段仍使用规定的英文枚举：

category
action
reason


协议字段名称也保持协议规定形式。


memory.content 是“忠实规范化”，

不是：

- 翻译任务
- 摘要创作任务
- 自由改写任务


应尽可能保留 latestUser 中原有的：

- 实体名称
- 对象名称
- 属性名称
- 数量
- 否定
- 关系
- 行为
- 目标
- 状态


只允许进行：

让句子能够脱离上下文独立理解所必需的最小改写。


禁止：

- 把用户具体实体翻译成另一种语言
- 用其他近义实体替换用户原词
- 把一个具体对象替换成另一个对象
- 为了语言自然度改变事实含义
- 把两个独立事实改写成比较关系
- 把“喜欢 A、不喜欢 B”改写成“更喜欢 A 而不是 B”
- 擅自扩大或缩小用户原本表达的范围


如果无法在不改变原始事实含义的情况下生成 memory：

返回 uncertain。


违反本节语言要求的输出：

会被程序拒绝写入数据库。


==================================================
【二十三、note】
==================================================

如果使用：

category = note

必须满足：

用户明确要求长期记住，
并且其他类别无法合理表示。


同时 operation 顶层必须：

"explicit": true


==================================================
【二十四、时间】
==================================================

只有 latestUser 明确支持时间信息时：

才可以输出可选 time。


涉及相对时间时：

可以根据 referenceTime 固定其时间含义。


不得编造：

- 日期
- 时间
- 数量
- 所有者
- 对象
- 因果关系


==================================================
【二十五、禁止保存】
==================================================

不要新增以下内容：

- 单纯问题
- 假设
- 虚构情境
- 单纯引用他人的事实
- 用户明确要求不要记录的内容
- 仅用于当前任务的临时参数
- 密码
- 验证码
- 密钥
- token
- 访问凭据


==================================================
【二十六、SKIP】
==================================================

如果某条 relatedMemory 与当前用户表达无关：

不要为了处理它而产生 UPDATE。


无需为每一个无关候选单独输出 skip。


如果整轮没有任何需要执行的长期记忆操作：

{"operations":[]}


==================================================
【二十七、UNCERTAIN】
==================================================

只有在确实存在长期记忆操作需求，

但是：

- 无法唯一确定 target
- 无法可靠理解修改内容
- 无法可靠计算新状态
- 多个旧候选无法排除歧义
- 无法在不改变事实含义的情况下生成安全结果

时才使用：

{
  "action": "uncertain"
}


不要因为：

relatedMemories 为空

就返回 uncertain。


不要因为：

后端召回了一些无关候选

就阻止一个明确的新事实 ADD。


==================================================
【二十八、数据库安全边界】
==================================================

UPDATE 只能使用 relatedMemories 中真实提供的：

targetId
version


expectedVersion：

必须等于对应记录的 version。


不得：

- 猜 ID
- 修改未展示记录
- 编造 version
- 同一轮重复修改同一个旧 ID


==================================================
【二十九、输出协议】
==================================================

只输出合法 JSON：

{
  "operations": [...]
}


最多 8 项。


ADD：

{
  "action": "add",
  "reason": "new",
  "memory": {
    "category": "...",
    "key": "...",
    "content": "..."
  }
}


UPDATE：

{
  "action": "update",
  "targetId": 实际ID,
  "expectedVersion": 实际version,
  "reason": "changed|corrected|refines|cancelled|completed|invalidated",
  "memory": {
    "category": "...",
    "key": "...",
    "content": "..."
  }
}


invalidated：

可以省略 memory。


note：

在 operation 顶层增加：

"explicit": true


SKIP：

{
  "action": "skip"
}


UNCERTAIN：

{
  "action": "uncertain"
}


不要输出：

source
sourceMessageId
source_reference
observedAt


这些字段全部由程序使用本轮真实用户消息自动填写。


如果没有操作：

{"operations":[]}


除了 JSON 以外：

不要输出解释；
不要输出 Markdown；
不要输出代码块；
不要输出任何其他文字。


你是本轮唯一最终语义决策器。

没有后续模型替你重新理解、
修复或审核语义结果。
"""

async def decide(
    model: JsonModel,
    turn: UserTurn,
    batch: RecallBatch,
):

    return await model.ask(
        "decision",
        PROMPT,
        {
            "latestUser": turn.latest_user,
            "referenceTime": turn.observed_at,
            "relatedMemories": list(
                batch.records
            ),
            "omittedMemoryCount": batch.omitted,
        },
        3200,
    )